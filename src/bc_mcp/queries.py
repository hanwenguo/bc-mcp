"""Read-only operations on a ledger snapshot. Results are JSON-ready dicts."""

from __future__ import annotations

import datetime
import os
import re
from collections import Counter, defaultdict
from decimal import Decimal
from pathlib import Path
from typing import Any

import beanquery
from beancount.core import amount as amount_mod
from beancount.core import data, inventory, position
from beancount.parser import printer
from beanquery import parser as bql_parser

from .ledger import Ledger, Snapshot
from .source import leading_comment_start, split_lines


class QueryError(Exception):
    """A read was refused; the message is meant for the agent."""


MAX_READ_BYTES = 2_000_000


def jsonable(value: Any) -> Any:
    if value is None or isinstance(value, (bool, int, str)):
        return value
    if isinstance(value, (Decimal, float)):
        return str(value)
    if isinstance(value, (datetime.date, datetime.datetime)):
        return value.isoformat()
    if isinstance(value, inventory.Inventory):
        return [str(pos) for pos in value]
    if isinstance(value, (amount_mod.Amount, position.Position, position.Cost)):
        return str(value)
    if isinstance(value, (set, frozenset)):
        return sorted(jsonable(v) for v in value)
    if isinstance(value, (list, tuple)):
        return [jsonable(v) for v in value]
    if isinstance(value, dict):
        return {str(k): jsonable(v) for k, v in value.items() if not str(k).startswith("__")}
    return str(value)


def _pattern(regex: str | None) -> re.Pattern | None:
    if not regex:
        return None
    try:
        return re.compile(regex)
    except re.error as exc:
        raise QueryError(f"invalid account regex {regex!r}: {exc}") from exc


def kind_of(entry) -> str:
    return type(entry).__name__.lower()


def entry_accounts(entry) -> list[str]:
    if isinstance(entry, data.Transaction):
        return [p.account for p in entry.postings]
    account = getattr(entry, "account", None)
    return [account] if account else []


def describe(snap: Snapshot, entry) -> dict[str, Any]:
    span = snap.span_for(entry)
    if span is not None and span.kind != kind_of(entry):
        span = None  # generated by a plugin at another directive's location (e.g. pad)
    if span is None:
        return {
            "id": None,
            "kind": kind_of(entry),
            "date": entry.date.isoformat(),
            "generated": True,
            "text": printer.format_entry(entry).rstrip(),
        }
    return {
        "id": span.id,
        "kind": span.kind,
        "date": span.date.isoformat(),
        "file": span.file,
        "line": span.start,
        "text": span.text,
    }


def _units_balances(snap: Snapshot, pattern: re.Pattern | None, as_of: datetime.date | None, depth: int | None):
    balances: dict[str, inventory.Inventory] = defaultdict(inventory.Inventory)
    for entry in snap.entries:
        if as_of and entry.date > as_of:
            break
        if not isinstance(entry, data.Transaction):
            continue
        for posting in entry.postings:
            if pattern and not pattern.search(posting.account):
                continue
            key = ":".join(posting.account.split(":")[:depth]) if depth else posting.account
            balances[key].add_amount(posting.units)
    return balances


def _inventory_strings(inv: inventory.Inventory) -> list[str]:
    return [str(pos.units) for pos in inv if pos.units.number != 0]


