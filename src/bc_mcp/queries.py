def ledger_info(ledger: Ledger, snap: Snapshot, git, policy: str | None) -> dict[str, Any]:
    counts = Counter(kind_of(e) for e in snap.entries)
    dated = [e.date for e in snap.entries if not isinstance(e, (data.Open, data.Commodity))]
    commodities = sorted({e.currency for e in snap.entries if isinstance(e, data.Commodity)})
    other_files = []
    for dirpath, dirnames, filenames in os.walk(ledger.root):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for name in sorted(filenames):
            rel = Path(dirpath, name).relative_to(ledger.root).as_posix()
            if not name.startswith(".") and rel not in snap.files:
                other_files.append(rel)
        if len(other_files) > 200:
            break
    layout = ledger.cfg.layout
    return {
        "title": snap.options.get("title"),
        "operating_currencies": snap.options.get("operating_currency", []),
        "commodities": commodities,
        "main_file": ledger.cfg.main,
        "ledger_files": snap.files,
        "other_files": other_files[:200],
        "entry_counts": dict(sorted(counts.items())),
        "date_range": [min(dated).isoformat(), max(dated).isoformat()] if dated else None,
        "errors": len(snap.errors),
        "layout": {
            "dated_file": layout.dated_file,
            "year_index": layout.year_index,
            "accounts_file": layout.accounts_file,
        },
        "git": {"head": git.head(), "uncommitted": git.dirty()} if git and git.available else None,
        "policy": policy,
    }


def list_accounts(snap: Snapshot, account: str | None, include_closed: bool, with_balances: bool) -> dict[str, Any]:
    pattern = _pattern(account)
    opens: dict[str, data.Open] = {}
    closes: dict[str, datetime.date] = {}
    used: Counter[str] = Counter()
    for entry in snap.entries:
        if isinstance(entry, data.Open):
            opens[entry.account] = entry
        elif isinstance(entry, data.Close):
            closes[entry.account] = entry.date
        elif isinstance(entry, data.Transaction):
            used.update(p.account for p in entry.postings)
    balances = _units_balances(snap, pattern, None, None) if with_balances else {}
    rows = []
    for name in sorted(opens):
        if pattern and not pattern.search(name):
            continue
        if name in closes and not include_closed:
            continue
        entry = opens[name]
        row: dict[str, Any] = {
            "account": name,
            "open": entry.date.isoformat(),
            "currencies": entry.currencies or [],
            "postings": used[name],
        }
        if name in closes:
            row["close"] = closes[name].isoformat()
        if entry.booking:
            row["booking"] = str(entry.booking.name)
        if with_balances:
            row["balance"] = _inventory_strings(balances.get(name, inventory.Inventory()))
        rows.append(row)
    return {"count": len(rows), "accounts": rows}


def balances(snap: Snapshot, account: str | None, as_of: datetime.date | None, depth: int | None) -> dict[str, Any]:
    if depth is not None and depth < 1:
        raise QueryError("depth must be at least 1")
    pattern = _pattern(account)
    result = _units_balances(snap, pattern, as_of, depth)
    totals = inventory.Inventory()
    rows = []
    for name in sorted(result):
        amounts = _inventory_strings(result[name])
        if amounts:
            rows.append({"account": name, "balance": amounts})
            totals.add_inventory(result[name])
    return {
        "as_of": (as_of.isoformat() if as_of else "latest") + " (end of day, includes entries on that date)",
        "accounts": rows,
        "total": _inventory_strings(totals),
        "note": "Units only; currencies are not converted. Liabilities and income are negative.",
    }


def find_entries(
    snap: Snapshot,
    *,
    start_date: datetime.date | None = None,
    end_date: datetime.date | None = None,
    kind: str | None = None,
    account: str | None = None,
    text: str | None = None,
    tag: str | None = None,
    link: str | None = None,
    flag: str | None = None,
    min_amount: Decimal | None = None,
    max_amount: Decimal | None = None,
    currency: str | None = None,
    limit: int = 50,
    oldest_first: bool = False,
) -> dict[str, Any]:
    pattern = _pattern(account)
    needle = text.lower() if text else None
    tag = tag.lstrip("#") if tag else None
    link = link.lstrip("^") if link else None
    matches = []
    for entry in snap.entries:
        if start_date and entry.date < start_date:
            continue
        if end_date and entry.date > end_date:
            continue
        if kind and kind_of(entry) != kind.lower():
            continue
        if pattern and not any(pattern.search(a) for a in entry_accounts(entry)):
            continue
        if tag and tag not in (getattr(entry, "tags", None) or ()):
            continue
        if link and link not in (getattr(entry, "links", None) or ()):
            continue
        if flag and getattr(entry, "flag", None) != flag:
            continue
        if min_amount is not None or max_amount is not None or currency:
            if not _amount_matches(entry, min_amount, max_amount, currency):
                continue
        if needle:
            span = snap.span_for(entry)
            haystack = span.text if span else printer.format_entry(entry)
            if needle not in haystack.lower():
                continue
        matches.append(entry)
    if not oldest_first:
        matches.reverse()
    limit = max(1, min(limit, 500))
    return {
        "total": len(matches),
        "returned": min(len(matches), limit),
        "entries": [describe(snap, e) for e in matches[:limit]],
    }


def _amount_matches(entry, low: Decimal | None, high: Decimal | None, currency: str | None) -> bool:
    if isinstance(entry, data.Transaction):
        amounts = [p.units for p in entry.postings if p.units is not None]
    elif isinstance(entry, data.Balance):
        amounts = [entry.amount]
    elif isinstance(entry, data.Price):
        amounts = [entry.amount]
    else:
        return False
    for amt in amounts:
        if amt.number is None or (currency and amt.currency != currency):
            continue
        number = abs(amt.number)
        if (low is None or number >= low) and (high is None or number <= high):
            return True
    return False


def get_entry(ledger: Ledger, snap: Snapshot, entry_id: str, context_lines: int) -> dict[str, Any]:
    span = snap.spans.get(entry_id)
    if span is None:
        raise QueryError(f"no entry with id {entry_id!r}; IDs change when an entry is edited, so search again")
    lines = split_lines(snap.texts.get(span.file, ""))
    comment_start = leading_comment_start(lines, span.start - 1)
    context = max(0, min(context_lines, 50))
    result: dict[str, Any] = {
        "id": span.id,
        "kind": span.kind,
        "date": span.date.isoformat(),
        "file": span.file,
        "line": span.start,
        "end_line": span.end,
        "text": span.text,
        "leading_comments": "\n".join(lines[comment_start : span.start - 1]) or None,
    }
    if context:
        result["before"] = "\n".join(lines[max(0, comment_start - context) : comment_start])
        result["after"] = "\n".join(lines[span.end : span.end + context])
    return result


# Statements that only read the loaded entries. CREATE TABLE ... USING and INSERT are refused: a USING
# source can open any file the server can read (e.g. 'csv:///etc/...').
READ_STATEMENTS = (bql_parser.ast.Select, bql_parser.ast.Balances, bql_parser.ast.Journal, bql_parser.ast.Print)


def run_query(snap: Snapshot, query: str, limit: int) -> dict[str, Any]:
    try:
        statement = bql_parser.parse(query)
    except Exception as exc:
        raise QueryError(f"BQL error: {exc}") from exc
    if not isinstance(statement, READ_STATEMENTS):
        raise QueryError("only SELECT, BALANCES, JOURNAL and PRINT queries are allowed")
    try:
        conn = beanquery.connect("beancount:", entries=snap.entries, errors=[], options=snap.options)
        cursor = conn.execute(statement)
        columns, rows = cursor.description, cursor.fetchall()
    except Exception as exc:  # beanquery raises a variety of compile and evaluation errors
        raise QueryError(f"BQL error: {exc}") from exc
    limit = max(1, min(limit, 5000))
    return {
        "columns": [c.name for c in columns],
        "rows": [[jsonable(v) for v in row] for row in rows[:limit]],
        "row_count": len(rows),
        "truncated": len(rows) > limit,
    }


def validate(snap: Snapshot) -> dict[str, Any]:
    return {"ok": not snap.errors, "errors": [e.as_dict() for e in snap.errors]}


def read_file(ledger: Ledger, path: str, start_line: int, end_line: int | None) -> dict[str, Any]:
    rel = ledger.rel(ledger.root / path)
    if rel is None or any(part.startswith(".") for part in Path(rel).parts):
        raise QueryError(f"{path!r} is outside the ledger directory or hidden")
    full = ledger.root / rel
    if not full.is_file():
        raise QueryError(f"{rel} is not a file")
    if full.stat().st_size > MAX_READ_BYTES:
        raise QueryError(f"{rel} is larger than {MAX_READ_BYTES} bytes")
    try:
        lines = full.read_text().split("\n")
    except UnicodeDecodeError as exc:
        raise QueryError(f"{rel} is not a text file") from exc
    if lines and lines[-1] == "":
        lines.pop()
    start = max(1, start_line)
    end = len(lines) if end_line is None else min(end_line, len(lines))
    return {
        "path": rel,
        "start_line": start,
        "end_line": end,
        "total_lines": len(lines),
        "text": "\n".join(lines[start - 1 : end]),
    }
